CREATE OR REPLACE PROCEDURE SP_RETURN_ASSET
(
    P_ASSIGN_ID NUMBER
)
AS
BEGIN
    UPDATE TBL_ASSET_ASSIGN_TRN
    SET RETURN_DATE = SYSDATE
    WHERE ASSIGN_ID = P_ASSIGN_ID;

    UPDATE TBL_ASSET_MST
    SET STATUS = 'AVAILABLE'
    WHERE ASSET_ID =
    (
        SELECT ASSET_ID
        FROM TBL_ASSET_ASSIGN_TRN
        WHERE ASSIGN_ID = P_ASSIGN_ID
    );

    COMMIT;
END;
